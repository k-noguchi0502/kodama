#!/bin/bash
# Build an Arch package and a pacman repo database from a release binary.
#
#   packaging/arch-package.sh [binary]
#
# Writes dist/kodama-<version>-1-x86_64.pkg.tar.zst and dist/kodama.db.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
version=$(tr -d '[:space:]' < "$root/VERSION")
pkgrel=1
pkgver="$version-$pkgrel"
name=kodama
arch=x86_64
url=https://github.com/k-noguchi0502/kodama
desc='A GPU-accelerated terminal emulator written from scratch in Rust'
binary=${1:-$root/target/release/kodama}
outfile="$root/dist/${name}-${pkgver}-${arch}.pkg.tar.zst"

if [ ! -f "$binary" ]; then
  echo "arch-package.sh: binary not found: $binary" >&2
  exit 1
fi

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT
pkg=$tmpdir/pkg
mkdir -p \
  "$pkg/usr/bin" \
  "$pkg/usr/share/applications" \
  "$pkg/usr/share/icons/hicolor/512x512/apps" \
  "$pkg/usr/share/licenses/$name" \
  "$pkg/usr/share/doc/$name/examples" \
  "$pkg/usr/share/kodama/lang"

install -Dm755 "$binary" "$pkg/usr/bin/kodama"
install -Dm644 "$root/assets/kodama.desktop" "$pkg/usr/share/applications/kodama.desktop"
install -Dm644 "$root/assets/kodama.png" "$pkg/usr/share/icons/hicolor/512x512/apps/kodama.png"
install -Dm644 "$root/LICENSE" "$pkg/usr/share/licenses/$name/LICENSE"
find "$root/examples" -maxdepth 1 -type f -exec install -Dm644 {} "$pkg/usr/share/doc/$name/examples/" \;
find "$root/lang" -maxdepth 1 -type f -name '*.lua' -exec install -Dm644 {} "$pkg/usr/share/kodama/lang/" \;

isize=$(find "$pkg/usr" -type f -printf '%s\n' | awk '{s += $1} END {print s}')
builddate=$(date -u +%s)

cat >"$pkg/.PKGINFO" <<EOF
# Generated by packaging/arch-package.sh
pkgname = $name
pkgbase = $name
xdata = pkgtype=pkg
pkgver = $pkgver
pkgdesc = $desc
url = $url
builddate = $builddate
packager = Kodama <$url>
size = $isize
arch = $arch
license = MIT
depend = fontconfig
depend = glibc
depend = libgcc
depend = libglvnd
depend = libx11
depend = libxcursor
depend = libxi
depend = libxkbcommon
depend = libxkbcommon-x11
depend = vulkan-icd-loader
depend = wayland
optdepend = vulkan-driver: Vulkan GPU driver
EOF

mkdir -p "$root/dist"
(cd "$pkg" && bsdtar --zstd -cf "$outfile" .PKGINFO usr)

csize=$(stat -c %s "$outfile")
sha=$(sha256sum "$outfile" | awk '{print $1}')
dbdir="$tmpdir/db/${name}-${pkgver}"
mkdir -p "$dbdir"
cat >"$dbdir/desc" <<EOF
%FILENAME%
$(basename "$outfile")

%NAME%
$name

%BASE%
$name

%VERSION%
$pkgver

%DESC%
$desc

%CSIZE%
$csize

%ISIZE%
$isize

%SHA256SUM%
$sha

%URL%
$url

%LICENSE%
MIT

%ARCH%
$arch

%BUILDDATE%
$builddate

%PACKAGER%
Kodama <$url>

%DEPENDS%
fontconfig
glibc
libgcc
libglvnd
libx11
libxcursor
libxi
libxkbcommon
libxkbcommon-x11
vulkan-icd-loader
wayland

%OPTDEPENDS%
vulkan-driver: Vulkan GPU driver
EOF

# The file is gzip. Its asset name is kodama.db so it does not also match
# the release archive glob (*.tar.gz) and get uploaded twice.
tar -C "$tmpdir/db" -czf "$root/dist/$name.db" "${name}-${pkgver}"
echo "Wrote $outfile"
echo "Wrote $root/dist/$name.db"
