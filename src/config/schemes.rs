#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schemes_are_found_by_loose_name() {
        assert_eq!(find("gruvbox-dark").unwrap().name, "Gruvbox Dark");
        assert_eq!(find("Rose Pine").unwrap().name, "Rosé Pine");
        assert_eq!(find("catppuccin_mocha").unwrap().name, "Catppuccin Mocha");
        assert!(find("no such scheme").is_none());
        let c = find("Gruvbox Dark").unwrap().colors();
        assert_eq!(c.background, [0x28, 0x28, 0x28]);
        assert_eq!(c.cursor, c.foreground);
        assert_eq!(c.brights[3], [0xfa, 0xbd, 0x2f]);
    }

    #[test]
    fn names_are_unique() {
        for (i, a) in SCHEMES.iter().enumerate() {
            assert!(
                SCHEMES[i + 1..]
                    .iter()
                    .all(|b| simplify(a.name) != simplify(b.name))
            );
        }
    }
}
