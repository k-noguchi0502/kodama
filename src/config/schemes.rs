//! Built-in color schemes, picked with `color_scheme = "Name"` (usually in
//! theme.lua, which can also define its own). Colors the
//! schemes don't define (dividers, tab bar, search highlights) are derived
//! from their palette.

use crate::config::{Colors, Rgb};

pub struct Scheme {
    pub name: &'static str,
    foreground: u32,
    background: u32,
    /// 0: the foreground.
    cursor: u32,
    selection: u32,
    ansi: [u32; 8],
    brights: [u32; 8],
}

const fn rgb(v: u32) -> Rgb {
    [(v >> 16) as u8, (v >> 8) as u8, v as u8]
}

pub fn mix(a: Rgb, b: Rgb, t: f32) -> Rgb {
    std::array::from_fn(|i| (a[i] as f32 + (b[i] as f32 - a[i] as f32) * t).round() as u8)
}

fn luminance(c: Rgb) -> f32 {
    0.2126 * c[0] as f32 + 0.7152 * c[1] as f32 + 0.0722 * c[2] as f32
}

impl Scheme {
    pub fn colors(&self) -> Colors {
        let (fg, bg) = (rgb(self.foreground), rgb(self.background));
        let cursor = (self.cursor != 0).then(|| rgb(self.cursor));
        derive(
            fg,
            bg,
            cursor,
            Some(rgb(self.selection)),
            self.ansi.map(rgb),
            self.brights.map(rgb),
        )
    }
}

/// A full set of colors from a scheme's palette; cursor and selection
/// default to the foreground and a foreground-tinted background.
pub fn derive(
    fg: Rgb,
    bg: Rgb,
    cursor: Option<Rgb>,
    selection: Option<Rgb>,
    ansi: [Rgb; 8],
    brights: [Rgb; 8],
) -> Colors {
    let dark = luminance(bg) < 128.0;
    Colors {
        foreground: fg,
        background: bg,
        cursor: cursor.unwrap_or(fg),
        selection: selection.unwrap_or(mix(bg, fg, 0.2)),
        split: mix(bg, fg, 0.25),
        active_border: ansi[4],
        active_background: mix(bg, fg, 0.08),
        search_match: ansi[3],
        search_current: mix(ansi[1], ansi[3], 0.5),
        tab_bar: if dark {
            mix(bg, [0, 0, 0], 0.25)
        } else {
            mix(bg, fg, 0.08)
        },
        tab_active: ansi[4],
        tab_inactive: mix(bg, fg, 0.1),
        ansi,
        brights,
    }
}

/// Whether two names mean the same scheme.
pub fn same(a: &str, b: &str) -> bool {
    simplify(a) == simplify(b)
}

/// Lowercase with spaces, dashes and underscores dropped, so "Tokyo Night",
/// "tokyo-night" and "tokyonight" name the same scheme.
fn simplify(name: &str) -> String {
    name.chars()
        .filter(|c| !matches!(c, ' ' | '-' | '_'))
        .flat_map(char::to_lowercase)
        .map(|c| if c == 'é' { 'e' } else { c })
        .collect()
}

pub fn find(name: &str) -> Option<&'static Scheme> {
    let want = simplify(name);
    SCHEMES.iter().find(|s| simplify(s.name) == want)
}

/// A scheme by name: one of `custom` (from theme.lua) first, then a
/// built-in one. Returns its proper name and colors.
pub fn resolve(custom: &[(String, Colors)], name: &str) -> Option<(String, Colors)> {
    custom
        .iter()
        .find(|(n, _)| same(n, name))
        .cloned()
        .or_else(|| find(name).map(|s| (s.name.to_string(), s.colors())))
}

macro_rules! scheme {
    ($name:literal, $fg:literal, $bg:literal, $cursor:literal, $sel:literal,
     [$($a:literal),*], [$($b:literal),*]) => {
        Scheme {
            name: $name,
            foreground: $fg,
            background: $bg,
            cursor: $cursor,
            selection: $sel,
            ansi: [$($a),*],
            brights: [$($b),*],
        }
    };
}

